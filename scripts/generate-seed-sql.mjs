// Generates supabase/migrations/002_seed.sql from data/seed-questions.json.
// Usage: npm run generate:seed
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const questions = JSON.parse(readFileSync(join(root, 'data/seed-questions.json'), 'utf8'));

const sql = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const rows = questions
  .map(
    (q) =>
      `  (${sql(q.id)}, ${sql(q.question_text)}, ${sql(q.hint)}, ${q.correct_lat}, ${q.correct_lng}, ${sql(
        q.correct_label,
      )}, ${sql(q.category)}, ${sql(q.difficulty)})`,
  )
  .join(',\n');

const out = `-- Generated by scripts/generate-seed-sql.mjs from data/seed-questions.json — do not edit by hand.
-- Seeds the initial question bank and schedules rounds for the next 30 days (UTC).

INSERT INTO questions (id, question_text, hint, correct_lat, correct_lng, correct_label, category, difficulty)
VALUES
${rows}
ON CONFLICT (id) DO NOTHING;

SELECT generate_daily_rounds((now() AT TIME ZONE 'utc')::date, 30);
`;

writeFileSync(join(root, 'supabase/migrations/002_seed.sql'), out);
console.log(`Wrote ${questions.length} questions to supabase/migrations/002_seed.sql`);
